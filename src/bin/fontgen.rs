/// Mỗi ký tự gồm 16 hàng (từ trên xuống dưới), mỗi hàng 1 byte (bit 7 = trái, bit 0 = phải)
/// Hàm này tự động lật bit sang chuẩn Little-Endian của `gfx_draw_char16` (bit 0 = cột x=0 bên trái)
fn pack_8x16(rows: [u8; 16]) -> (u64, u64) {
    let flip = |b: u8| -> u64 { b.reverse_bits() as u64 };
    let mut top = 0u64;
    let mut bot = 0u64;
    for y in 0..8 {
        top |= flip(rows[y]) << (y * 8);
        bot |= flip(rows[y + 8]) << (y * 8);
    }
    (top, bot)
}

